#!/bin/zsh
set -euo pipefail
root=${0:A:h:h}
source "$root/Scripts/manifest.sh"
output=${1:-$root/Shortcuts/shortcut-payload.sh}
if [[ $output == --check ]]; then
  temp=$(mktemp)
  trap 'rm -f "$temp"' EXIT
  "$0" "$temp"
  cmp -s "$temp" "$root/Shortcuts/shortcut-payload.sh" || { print -u2 '载荷过期，请执行 make shortcut'; exit 1; }
  print '载荷与正式源码一致'
  exit
fi
{
  print -r -- '#!/bin/zsh'
  print -r -- '# Generated by Scripts/generate-shortcut.sh; edit formal sources instead.'
  cat <<'HEADER'
set -euo pipefail
umask 077
payload_dir=$(mktemp -d "${TMPDIR:-/tmp}/mousescrolltoggle.XXXXXX")
trap 'rm -rf "$payload_dir"' EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
mkdir -p "$payload_dir/Scripts" "$payload_dir/Sources"
HEADER
  for f in $bundle_files; do
    delimiter="MST_$(shasum -a 256 "$root/$f" | cut -d ' ' -f1)"
    print -r -- "cat > \"\$payload_dir/$f\" <<'$delimiter'"
    cat "$root/$f"
    print -r -- "$delimiter"
  done
  print -r -- '/bin/zsh "$payload_dir/Scripts/click.sh"'
} > "$output"
chmod 700 "$output"
